import { chromium } from 'playwright';
import fs from 'node:fs';
const dir = 'docs/design-drafts/training-flow-v5/review';
const base = 'http://localhost:8013/docs/design-drafts/';
const report = { checks: [], errors: [], screenshots: [], requests: [], migrations: 'Review-only in-memory session; no database or save system.' };
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1080 }, hasTouch: true });
ctx.setDefaultTimeout(15000);
const page = await ctx.newPage();
page.on('pageerror', e => report.errors.push(e.message));
page.on('request', r => { if (/\/api\//.test(r.url())) report.requests.push(r.url()); });
function assert(value, message) { if (!value) throw Error(message); report.checks.push(message); }
async function screenshot(name, target = page.locator('#stage')) {
  await page.waitForTimeout(1100);
  await target.screenshot({ path: dir + '/' + name + '.png' }); report.screenshots.push(name + '.png');
}
async function ready() { await page.waitForFunction(() => window.flowPreview?.ready); }
async function data() { return page.evaluate(() => ({ a: flowPreview.session.snapshot('A'), b: flowPreview.session.snapshot('B'), receipt: flowPreview.session.battle('A'), trial: flowPreview.session.trial('A') })); }
await page.goto(base + 'training-flow-v5/index.html?screen=victory');
await ready();
let current = await data();
assert(current.receipt === null && current.trial === null, 'Opening a result screen never creates a receipt');
assert((await page.locator('#ui-empty').innerText()).includes('Zatím'), 'No receipt has an explicit empty state');
await screenshot('journey-empty');
await page.click('#simulate-steady');
assert((await page.locator('#ui-mana').innerText()) === '0', 'No improvement shows the real zero-mana receipt');
await screenshot('journey-no-bonus');
await page.click('#reset');
await page.click('#simulate-win');
current = await data();
assert(current.receipt.reward.mana === 1 && current.receipt.reward.improvement > 0, 'Explicit simulation uses the runtime personal bonus');
assert(current.a.fox.status === 'locked', 'An ordinary battle does not rescue the fox');
assert((await page.locator('#ui-speed').innerText()).includes('9,2 s') && (await page.locator('#ui-speed').innerText()).includes('6,6 s'), 'Victory shows the receipt median before and after');
assert(await page.locator('#ui-journey').getAttribute('data-target-id') === current.receipt.targetId, 'Victory path identifies the battle target');
await screenshot('journey-victory');
const pathBounds = await page.locator('#ui-journey').boundingBox();
await page.hover('#ui-journey'); await screenshot('journey-hover');
await page.mouse.down(); await screenshot('journey-pressed');
const pressedBounds = await page.locator('#ui-journey').boundingBox();
assert(pathBounds.x === pressedBounds.x && pathBounds.y === pressedBounds.y && pathBounds.width === pressedBounds.width, 'Journey surface moves inside a stable hit area');
await page.mouse.move(4, 4); await page.mouse.up();
assert(await page.locator('#external').isHidden(), 'Pointer-out does not navigate');
await page.click('#ui-journey');
await page.waitForFunction(() => document.querySelector('#external iframe')?.contentWindow.catacombPreview);
let parent = page.frames().find(f => f.url().includes('catacombs-access-v1/'));
assert(await parent.evaluate(() => catacombPreview.session === window.top.flowPreview.session), 'Standalone child and catacombs share the same session instance');
assert(await parent.evaluate(() => catacombPreview.focus === 'B1' && catacombPreview.owner === 'A'), 'Path navigation preserves owner and target');
assert(await parent.locator('[data-gate="B1"]').getAttribute('class').then(s => s.includes('open')), 'Victory and catacomb lock agree');
await parent.click('[data-target="B2"]');
assert(await page.evaluate(() => flowPreview.session.preference('A').targetId === 'B2' && flowPreview.session.preference('A').mode === 'practice'), 'Choosing a module changes target only');
await parent.click('[data-gate="B2"]');
assert((await parent.locator('#guideTitle').innerText()).includes('zkouška'), 'Fast module without basic exam leads to the exam guide');
await screenshot('journey-exam-link');
await page.click('#externalBack');
// The last battle remains about B1 even after changing the remembered target.
assert(await page.locator('#ui-journey').getAttribute('data-target-id') === 'B1', 'A past receipt is not relabelled as the newly selected target');
await page.click('#catacombs');
await parent.click('[data-target="B1"]');
await page.click('#externalBack');
await page.click('#simulate-trial');
current = await data();
assert(current.trial.kind === 'rescue' && current.trial.attackAfter === current.a.fox.baseAttack && current.a.fox.status === 'at_pythia', 'First trial rescues at catalog strength and waits at Pythia');
assert((await page.locator('#ui-petStats').innerText()).trim() === '6', 'First rescue shows actual catalog attack 6');
assert(await page.locator('#ui-trials [data-trial]').count() === current.a.trials.length, 'Runes represent only the actual challenge list');
await screenshot('journey-rescue');
const firstId = current.trial.id;
await page.click('#ui-action');
await page.waitForFunction(() => document.querySelector('#external iframe')?.contentWindow.catacombPreview);
parent = page.frames().find(f => f.url().includes('catacombs-access-v1/'));
assert((await parent.locator('#guideTitle').innerText()).includes('Pythie'), 'Rescue action opens the shared Pythia step');
assert((await data()).a.fox.status === 'at_pythia' && (await data()).trial.id === firstId, 'Opening Pythia neither binds nor awards again');
await screenshot('journey-pythia');
await page.click('#externalBack');
await page.click('#simulate-bind');
assert((await data()).a.fox.status === 'owned', 'Only explicit binding simulation changes ownership');
await screenshot('journey-owned');
for (let i = 0; i < 4 && !(await data()).a.readiness.ready; i++) await page.click('#simulate-win');
assert((await data()).a.readiness.ready, 'Runtime readiness enables the later challenge');
await page.click('#simulate-trial');
current = await data();
assert(current.trial.kind === 'upgrade' && current.trial.attackAfter === current.trial.attackBefore + 1, 'Later challenge displays the real one-point upgrade');
assert(current.a.state === 'mastery' && current.a.fox.attack === 7, 'Mastery trial and actual pet strength agree');
await screenshot('journey-upgrade');
await page.click('[data-screen="coop"]');
assert(!(await page.locator('#ui-practice0').isDisabled()), 'Training stays selectable after mastery');
await page.click('#ui-practice0');
assert(await page.locator('#ui-action').isDisabled(), 'One child cannot confirm co-op for both');
await page.click('#ui-progress1');
assert(!(await page.locator('#ui-action').isDisabled()), 'Both children can independently confirm their modes');
const battleId = (await data()).receipt.id;
await page.click('#ui-action');
await page.waitForFunction(() => document.querySelector('#external iframe')?.contentWindow.variants);
assert((await data()).receipt.id === battleId, 'Opening MathBoard does not fabricate a battle result');
await page.click('#externalBack');
for (const viewport of [{ width: 1024, height: 768 }, { width: 768, height: 1024 }]) {
  await page.setViewportSize(viewport);
  for (const screen of ['zyx', 'coop', 'victory', 'pet']) {
    await page.click('[data-screen="' + screen + '"]');
    const targets = await page.locator('#content button').evaluateAll(es => es.map(e => ({ w: e.getBoundingClientRect().width, h: e.getBoundingClientRect().height })));
    assert(targets.every(t => t.w >= 44 && t.h >= 44), 'Touch targets at ' + viewport.width + ': ' + screen);
    await screenshot('journey-' + viewport.width + '-' + screen);
  }
}
await page.click('#words');
await screenshot('journey-no-words-pet');
await page.click('[data-screen="victory"]');
await screenshot('journey-no-words-victory');
const trialId = (await data()).trial.id;
await page.selectOption('#owner', 'B');
assert(await page.locator('#ui-empty').isVisible(), 'Player B does not inherit player A battle receipt');
await page.click('[data-screen="pet"]');
assert(await page.locator('#ui-fox').getAttribute('class').then(c => c.includes('fox-future')), 'Player B does not inherit player A fox');
await page.selectOption('#owner', 'A');
assert((await data()).trial.id === trialId, 'Rerendering and owner switching do not award again');
assert((await page.evaluate(() => Object.keys(localStorage).concat(Object.keys(sessionStorage)))).length === 0, 'Both storage namespaces remain empty');
assert(report.requests.length === 0, 'No save API requests');
assert(report.errors.length === 0, 'No runtime errors in standalone flow');
// Opposite embedding direction, including first route for player B.
const p = await ctx.newPage();
p.on('pageerror', e => report.errors.push(e.message));
await p.goto(base + 'catacombs-access-v1/index.html');
await p.waitForFunction(() => window.catacombPreview);
await p.click('[data-owner="B"]'); await p.click('#demoWin');
await p.waitForFunction(() => document.querySelector('#flow')?.contentWindow.flowPreview?.ready);
await p.waitForFunction(() => document.querySelector('#flow')?.contentWindow.flowPreview?.state.owner === 'B');
const child = p.frames().find(f => f.url().includes('training-flow-v5/'));
assert(await child.evaluate(() => flowPreview.state.owner === 'B' && flowPreview.state.screen === 'victory'), 'Parent forwards the first route for player B after iframe load');
assert(await child.evaluate(() => flowPreview.session === window.top.catacombPreview.session), 'Parent and v5 child share identity');
assert(await child.locator('header').isHidden() && await child.locator('#simulation').isHidden(), 'Embedded mode hides review controls');
assert(await child.locator('#ui-portrait .number').innerText() === '2', 'Embedded result displays the correct portrait');
await screenshot('journey-embedded-B', p.locator('#flowHost'));
await child.click('#ui-journey');
assert(await p.locator('#fit').isVisible() && await p.evaluate(() => catacombPreview.owner === 'B' && catacombPreview.focus === 'B1'), 'Embedded path returns to the same owner and module');
assert(report.errors.length === 0, 'No runtime errors in either embedding direction');
// First ever external frame can be Pythia: no previously loaded catacomb module may be required.
const direct = await ctx.newPage(); direct.on('pageerror', e => report.errors.push(e.message));
await direct.goto(base + 'training-flow-v5/index.html?screen=victory');
await direct.waitForFunction(() => window.flowPreview?.ready);
await direct.click('#simulate-win'); await direct.click('#simulate-trial'); await direct.click('#ui-action');
await direct.waitForFunction(() => document.querySelector('#external iframe')?.contentWindow.catacombPreview?.ready);
const directParent = direct.frames().find(f => f.url().includes('catacombs-access-v1/'));
await directParent.waitForFunction(() => document.querySelector('#guideTitle')?.textContent === 'U Pythie' && !document.querySelector('#guide').hidden);
assert(await direct.evaluate(() => flowPreview.session.snapshot('A').fox.status === 'at_pythia'), 'First external route reaches Pythia without binding or losing the rescue');
assert(report.errors.length === 0, 'Ready handshakes complete without runtime errors');
fs.writeFileSync(dir + '/journey-verification.json', JSON.stringify(report, null, 2));
await browser.close();
console.log(JSON.stringify({ checks: report.checks.length, screenshots: report.screenshots.length, errors: report.errors }));
